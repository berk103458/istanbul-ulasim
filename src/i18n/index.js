let currentLang = "tr";

function setLabel(selector, key, alsoTitle = true) {
  const el = document.querySelector(selector);
  if (!el) return;
  const label = t(key);
  el.setAttribute("aria-label", label);
  if (alsoTitle) el.title = label;
}

function syncDomLang() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = currentLang;
  document.title = t("app.title");

  const srH1 = document.querySelector("h1.sr-only");
  if (srH1) srH1.textContent = t("app.title");

  const navMap = {
    yakin: "nav.yakin",
    rota: "nav.rota",
    otobus: "nav.otobus",
    rayli: "nav.rayli",
    vapur: "nav.vapur",
  };
  document.querySelectorAll("#sekmeler button[data-sekme]").forEach((btn) => {
    const key = navMap[btn.dataset.sekme];
    const span = btn.querySelector("span:last-child");
    if (key && span) span.textContent = t(key);
  });

  setLabel("#sekmeler", "nav.mainMenu", false);
  setLabel("#harita", "map.regionLabel", false);
  setLabel("#panel", "panel.regionLabel", false);
  setLabel("#tutamak", "panel.dragHandle", true);
  setLabel("#trafikBtn", "traffic.title", true);
  setLabel("#isparkBtn", "map.isparkTitle", true);
  setLabel("#katmanBtn", "map.layersTitle", true);
  setLabel("#konumBtn", "map.locationTitle", true);

  const secimYazi = document.querySelector("#secimBandiYazi");
  if (secimYazi) secimYazi.textContent = t("route.tapMapHint");
  const secimIptal = document.querySelector("#secimIptal");
  if (secimIptal) secimIptal.textContent = t("common.cancel");
}

export function initLang() {
  let saved = null;
  try {
    saved = localStorage.getItem(LS_KEY);
  } catch {
    // ignore
  }
  if (saved === "tr" || saved === "en") {
    currentLang = saved;
  } else if (typeof navigator !== "undefined" && String(navigator.language || "").toLowerCase().startsWith("en")) {
    currentLang = "en";
  } else {
    currentLang = "tr";
  }
  syncDomLang();
  return currentLang;
}

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  currentLang = lang === "en" ? "en" : "tr";
  try {
    localStorage.setItem(LS_KEY, currentLang);
  } catch {
    // ignore
  }
  syncDomLang();
  return currentLang;
}

export function t(key, vars) {
  const dict = STRINGS[currentLang] || STRINGS.tr;
  let str = dict[key] ?? STRINGS.tr[key] ?? key;
  if (vars && typeof vars === "object") {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v ?? ""));
    }
  }
  return str;
}
